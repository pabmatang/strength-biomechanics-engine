/**
 * Returns a 100% reliable, verified image URL for a machine template or muscle group.
 * Strictly uses authentic manufacturer photography stored locally.
 */
export function getSafeMachineImageUrl(
  templateId?: string,
  muscleGroup?: string,
  candidateUrl?: string,
  brand?: string,
  equipmentCategory?: string
): string {
  // 1. Exact template match in verified machine photos catalog
  if (templateId && VERIFIED_MACHINE_IMAGES[templateId]) {
    return VERIFIED_MACHINE_IMAGES[templateId];
  }

  // 2. Candidate URL (ExerciseDB GIF, local image, authentic manufacturer asset)
  if (candidateUrl && candidateUrl.trim().length > 0) {
    const isTechnogym = (brand && brand.toLowerCase().includes('technogym')) || (templateId && templateId.toLowerCase().includes('technogym'));
    if (isTechnogym && candidateUrl.startsWith('/machines/') && !candidateUrl.includes('technogym')) {
      if (muscleGroup && TECHNOGYM_FALLBACK_IMAGES[muscleGroup]) {
        return TECHNOGYM_FALLBACK_IMAGES[muscleGroup];
      }
      return '/machines/technogym_pure_chest_press.png';
    }
    return candidateUrl;
  }

  // 3. Fallback specifically for Technogym machines
  const isTechnogym = (brand && brand.toLowerCase().includes('technogym')) || (templateId && templateId.toLowerCase().includes('technogym'));
  if (isTechnogym) {
    if (muscleGroup && TECHNOGYM_FALLBACK_IMAGES[muscleGroup]) {
      return TECHNOGYM_FALLBACK_IMAGES[muscleGroup];
    }
    return '/machines/technogym_pure_chest_press.png';
  }

  // 4. Fallback for Free Weights (Dumbbell, Barbell, Cable, Smith, Bodyweight)
  const isFreeWeight = equipmentCategory === 'dumbbell' || equipmentCategory === 'barbell' || equipmentCategory === 'cable' || equipmentCategory === 'smith' || equipmentCategory === 'none' ||
    (templateId && (templateId.includes('dumbbell') || templateId.includes('barbell') || templateId.includes('cable') || templateId.includes('smith') || templateId.includes('bodyweight')));

  if (isFreeWeight) {
    // Return standard ExerciseDB demonstration GIF based on category & muscle
    if (equipmentCategory === 'dumbbell' || (templateId && templateId.includes('dumbbell'))) {
      if (muscleGroup === 'shoulders') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/delts/dumbbell-lateral-raise.gif';
      if (muscleGroup === 'biceps') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/biceps/dumbbell-biceps-curl.gif';
      if (muscleGroup === 'triceps') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/triceps/dumbbell-seated-triceps-extension.gif';
      if (muscleGroup === 'chest') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/pectorals/dumbbell-bench-press.gif';
      if (muscleGroup === 'upper_back' || muscleGroup === 'lats') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/upper-back/dumbbell-reverse-grip-incline-bench-one-arm-row.gif';
      if (muscleGroup === 'quadriceps' || muscleGroup === 'glutes' || muscleGroup === 'hamstrings') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/glutes/dumbbell-romanian-deadlift.gif';
      return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/delts/dumbbell-lateral-raise.gif';
    }
    if (equipmentCategory === 'barbell' || (templateId && templateId.includes('barbell'))) {
      if (muscleGroup === 'chest') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/pectorals/barbell-bench-press.gif';
      if (muscleGroup === 'shoulders') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/delts/barbell-standing-close-grip-military-press.gif';
      if (muscleGroup === 'quadriceps' || muscleGroup === 'glutes') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/glutes/barbell-full-squat.gif';
      if (muscleGroup === 'upper_back') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/upper-back/barbell-bent-over-row.gif';
      return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/glutes/barbell-deadlift.gif';
    }
    if (equipmentCategory === 'cable' || (templateId && templateId.includes('cable'))) {
      if (muscleGroup === 'delts' || muscleGroup === 'shoulders') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/delts/cable-lateral-raise.gif';
      if (muscleGroup === 'triceps') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/triceps/cable-triceps-pushdown-v-bar.gif';
      if (muscleGroup === 'biceps') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/biceps/cable-bicep-curl.gif';
      if (muscleGroup === 'lats') return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/lats/cable-lat-pulldown-full-range-of-motion.gif';
      return 'https://cdn.jsdelivr.net/gh/JahelCuadrado/ExerciseGymGifsDB@v1.1.0/pectorals/cable-standing-fly.gif';
    }
    return '/machines/eleiko_bench.png';
  }

  // 5. Fallback to real manufacturer machine by muscle group
  if (muscleGroup && DEFAULT_MUSCLE_FALLBACK_IMAGES[muscleGroup]) {
    return DEFAULT_MUSCLE_FALLBACK_IMAGES[muscleGroup];
  }

  // 6. Global default
  return '/machines/technogym_pure_chest_press.png';
}
